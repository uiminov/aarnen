# -*- coding: utf-8 -*-
"""
Сборка файла "Ежедневный_отчёт_по_просрочке.xlsx" без Excel.

На вход:
  * файл "Прогнозы по кредитам" (колонки ОБЛАСТЬ / СУММА / Статус)
  * файл "Активные кредиты" (колонки Филиал / Область / Номер договора /
    Общая задолженность)

На выходе: та же книга отчёта, что и раньше, но с уже посчитанными цифрами
и БЕЗ попытки обновиться при открытии — её можно открыть на любом компьютере,
никаких папок рядом не требуется.

Работает на чистом Python (openpyxl + правка XML), Excel на сервере не нужен.
"""

from __future__ import annotations

import os
import re
import shutil
import tempfile
import zipfile
from collections import defaultdict
from datetime import datetime

import openpyxl

# --- 4 статуса, которые выбираются из выпадающего списка в файле филиалов ---
СТАТУСЫ = ("Дозвон", "Обещал", "Недозвон", "Объезд")

# --- 14 областей: строка в ПК_Просрочка (4..17) и индекс строки в sharedStrings ---
ОБЛАСТИ = [
    ("АНДИЖОН ВИЛОЯТИ", 225),
    ("БУХОРО ВИЛОЯТИ", 231),
    ("ЖИЗЗАХ ВИЛОЯТИ", 224),
    ("КАШКАДАРЁ ВИЛОЯТИ", 228),
    ("КОРАКАЛПОГИСТОН РЕСПУБЛИКАСИ", 229),
    ("НАВОИЙ ВИЛОЯТИ", 230),
    ("НАМАНГАН ВИЛОЯТИ", 226),
    ("САМАРКАНД ВИЛОЯТИ", 222),
    ("СИРДАРЁ ВИЛОЯТИ", 232),
    ("СУРХОНДАРЁ ВИЛОЯТИ", 223),
    ("ТОШКЕНТ ВИЛОЯТИ", 233),
    ("ТОШКЕНТ ШАХРИ", 234),
    ("ФАРГОНА ВИЛОЯТИ", 227),
    ("ХОРАЗМ ВИЛОЯТИ", 221),
]

# Список филиалов НЕ зашит: порядок строк на листе ПК_Портфель может быть любым,
# поэтому имена читаются из самого шаблона (см. _филиалы_из_шаблона).
ПК_ПОРТФЕЛЬ_ПЕРВАЯ_СТРОКА = 4
ПК_ПОРТФЕЛЬ_ПОСЛЕДНЯЯ_СТРОКА = 21


class ОшибкаФайла(Exception):
    """Понятная пользователю ошибка про присланный файл."""


# --------------------------------------------------------------------------
# чтение исходных файлов
# --------------------------------------------------------------------------

def _строки_листа(путь, имя_листа=None):
    wb = openpyxl.load_workbook(путь, data_only=True, read_only=True)
    try:
        ws = wb[имя_листа] if имя_листа else wb[wb.sheetnames[0]]
        return [list(r) for r in ws.iter_rows(values_only=True)]
    finally:
        wb.close()


def _найти_шапку(строки, обязательные):
    """Ищет строку-шапку: ту, где встречаются все нужные заголовки."""
    for i, r in enumerate(строки):
        if not r:
            continue
        ячейки = {str(c).strip() for c in r if c is not None}
        if all(о in ячейки for о in обязательные):
            заголовки = [str(c).strip() if c is not None else "" for c in r]
            return i, заголовки
    return None, None


def определить_тип(путь):
    """Что за файл прислали: 'просрочка', 'кредиты' или None."""
    try:
        строки = _строки_листа(путь)
    except Exception:
        return None
    i, _ = _найти_шапку(строки, ("ОБЛАСТЬ", "СУММА", "Статус"))
    if i is not None:
        return "просрочка"
    i, _ = _найти_шапку(строки, ("Филиал", "Общая задолженность"))
    if i is not None:
        return "кредиты"
    return None


def читать_просрочку(путь):
    """-> {область: {'Дозвон': (сумма, шт), ...}}, всего_строк"""
    строки = _строки_листа(путь)
    i, hdr = _найти_шапку(строки, ("ОБЛАСТЬ", "СУММА", "Статус"))
    if i is None:
        raise ОшибкаФайла(
            "В файле не нашлись колонки «ОБЛАСТЬ», «СУММА» и «Статус». "
            "Похоже, это не файл «Прогнозы по кредитам»."
        )
    iO, iS, iSt = hdr.index("ОБЛАСТЬ"), hdr.index("СУММА"), hdr.index("Статус")

    итог = defaultdict(lambda: {s: [0.0, 0] for s in СТАТУСЫ})
    всего = 0
    без_области = 0
    for r in строки[i + 1:]:
        if not r or len(r) <= max(iO, iS, iSt):
            continue
        обл = r[iO]
        if обл is None or not str(обл).strip():
            # строка без области — считаем отдельно, чтобы предупредить
            if r[iS] is not None:
                без_области += 1
            continue
        обл = str(обл).strip().upper()
        try:
            сумма = float(r[iS] or 0)
        except (TypeError, ValueError):
            сумма = 0.0
        ст = str(r[iSt]).strip() if r[iSt] is not None else ""
        ст = ст if ст in СТАТУСЫ else "Недозвон"
        итог[обл][ст][0] += сумма
        итог[обл][ст][1] += 1
        всего += 1

    if всего == 0:
        raise ОшибкаФайла("В файле нет ни одной строки с заполненной областью.")
    return итог, всего, без_области


def читать_кредиты(путь):
    """-> (портфель_по_областям, портфель_по_филиалам {филиал: (шт, сумма)})"""
    строки = _строки_листа(путь, "Активные кредиты 5_NEW") if _есть_лист(
        путь, "Активные кредиты 5_NEW") else _строки_листа(путь)
    i, hdr = _найти_шапку(строки, ("Филиал", "Общая задолженность"))
    if i is None:
        raise ОшибкаФайла(
            "В файле не нашлись колонки «Филиал» и «Общая задолженность». "
            "Похоже, это не файл «Активные кредиты»."
        )
    iF = hdr.index("Филиал")
    iSum = hdr.index("Общая задолженность")
    iO = hdr.index("Область") if "Область" in hdr else None
    iD = hdr.index("Номер договора") if "Номер договора" in hdr else None

    по_областям = defaultdict(float)
    по_филиалам = defaultdict(lambda: [0, 0.0])
    for r in строки[i + 1:]:
        if not r or len(r) <= iSum:
            continue
        if iD is not None and (len(r) <= iD or r[iD] is None):
            continue
        try:
            сумма = float(r[iSum] or 0)
        except (TypeError, ValueError):
            continue
        ф = str(r[iF]).strip() if r[iF] is not None else ""
        if ф:
            по_филиалам[ф][0] += 1
            по_филиалам[ф][1] += сумма
        if iO is not None and len(r) > iO and r[iO] is not None:
            о = str(r[iO]).strip().upper()
            if о:
                по_областям[о] += сумма

    if not по_филиалам:
        raise ОшибкаФайла("В файле кредитов не нашлось ни одной строки с данными.")
    return по_областям, по_филиалам


def _есть_лист(путь, имя):
    try:
        wb = openpyxl.load_workbook(путь, read_only=True)
        try:
            return имя in wb.sheetnames
        finally:
            wb.close()
    except Exception:
        return False


# --------------------------------------------------------------------------
# запись в книгу отчёта (правка XML напрямую — Power Query не ломается)
# --------------------------------------------------------------------------

def _ч(v):
    """Число -> текст для XML."""
    return repr(round(float(v), 2))


def _общие_строки(папка):
    """sharedStrings.xml -> список текстов (индекс = номер строки)."""
    путь = os.path.join(папка, "xl", "sharedStrings.xml")
    if not os.path.exists(путь):
        return []
    x = open(путь, encoding="utf-8").read()
    return [(m.group(1) or "") for m in
            re.finditer(r"<si>(?:<t[^>]*>(.*?)</t>|.*?)</si>", x, re.S)]


def _филиалы_из_шаблона(папка):
    """{номер строки: имя филиала} — берём как есть из листа ПК_Портфель."""
    строки_текстов = _общие_строки(папка)
    xml = open(os.path.join(папка, "xl", "worksheets", "sheet6.xml"),
               encoding="utf-8").read()
    итог = {}
    for r in range(ПК_ПОРТФЕЛЬ_ПЕРВАЯ_СТРОКА, ПК_ПОРТФЕЛЬ_ПОСЛЕДНЯЯ_СТРОКА + 1):
        m = re.search(r'<c r="A%d"[^>]*t="s"[^>]*><v>(\d+)</v></c>' % r, xml)
        if not m:
            continue
        idx = int(m.group(1))
        if idx < len(строки_текстов):
            имя = строки_текстов[idx].strip()
            if имя:
                итог[r] = имя
    return итог


def _заменить_ячейку(xml, ref, содержимое, стиль_из=None):
    """Заменяет ячейку (пустую или со значением) на новую с значением."""
    шаблон = re.compile(r'<c r="%s"(?:[^>]*?)(?:/>|>.*?</c>)' % ref, re.S)
    if not шаблон.search(xml):
        raise RuntimeError("не найдена ячейка %s" % ref)
    return шаблон.sub(lambda m: содержимое, xml, count=1)


def собрать_отчёт(файл_просрочки, файл_кредитов, шаблон, куда):
    """Главная функция: делает готовый файл отчёта."""
    просрочка, всего_строк, без_области = читать_просрочку(файл_просрочки)
    порт_обл, порт_фил = читать_кредиты(файл_кредитов)

    временная = tempfile.mkdtemp(prefix="report_")
    try:
        with zipfile.ZipFile(шаблон) as z:
            z.extractall(временная)

        # ---- лист ПК_Просрочка (sheet7): область × статус + портфель области ----
        p7 = os.path.join(временная, "xl", "worksheets", "sheet7.xml")
        xml = open(p7, encoding="utf-8").read()
        for n, (обл, sidx) in enumerate(ОБЛАСТИ):
            r = 4 + n
            d = просрочка.get(обл, {s: [0.0, 0] for s in СТАТУСЫ})
            значения = [
                ("B", d["Дозвон"][0]), ("C", d["Дозвон"][1]),
                ("D", d["Обещал"][0]), ("E", d["Обещал"][1]),
                ("F", d["Недозвон"][0]), ("G", d["Недозвон"][1]),
                ("H", d["Объезд"][0]), ("I", d["Объезд"][1]),
                ("J", порт_обл.get(обл, 0.0)),
            ]
            xml = _заменить_ячейку(
                xml, "A%d" % r, '<c r="A%d" s="88" t="s"><v>%d</v></c>' % (r, sidx))
            for кол, v in значения:
                xml = _заменить_ячейку(
                    xml, "%s%d" % (кол, r),
                    '<c r="%s%d"><v>%s</v></c>' % (кол, r, _ч(v)))
        open(p7, "w", encoding="utf-8").write(xml)

        # ---- лист ПК_Портфель (sheet6): филиал / кол-во / сумма / дата ----
        # ВАЖНО: имена филиалов берём из самого шаблона — порядок строк там
        # свой (по величине портфеля), и подставлять цифры «по своему списку»
        # нельзя, иначе они съедут между филиалами.
        p6 = os.path.join(временная, "xl", "worksheets", "sheet6.xml")
        xml6 = open(p6, encoding="utf-8").read()
        филиалы_шаблона = _филиалы_из_шаблона(временная)
        серийная_дата = (datetime.now() - datetime(1899, 12, 30)).days
        for r, фил in филиалы_шаблона.items():
            шт, сум = порт_фил.get(фил, [0, 0.0])
            for кол, v in (("B", шт), ("C", сум), ("D", серийная_дата)):
                стиль = ' s="87"' if кол == "D" else ""
                try:
                    xml6 = _заменить_ячейку(
                        xml6, "%s%d" % (кол, r),
                        '<c r="%s%d"%s><v>%s</v></c>' % (кол, r, стиль, _ч(v)))
                except RuntimeError:
                    pass  # такой ячейки в шаблоне нет — пропускаем
        open(p6, "w", encoding="utf-8").write(xml6)
        нет_в_отчёте = sorted(set(порт_фил) - set(филиалы_шаблона.values()))

        # ---- выключаем автообновление: файл должен открываться где угодно ----
        pc = os.path.join(временная, "xl", "connections.xml")
        if os.path.exists(pc):
            c = open(pc, encoding="utf-8").read()
            c = c.replace('refreshOnLoad="1"', 'refreshOnLoad="0"')
            open(pc, "w", encoding="utf-8").write(c)

        # ---- пересчёт формул при открытии (Excel сделает это сам) ----
        pw = os.path.join(временная, "xl", "workbook.xml")
        w = open(pw, encoding="utf-8").read()
        if "fullCalcOnLoad" not in w:
            w = w.replace("<calcPr ", '<calcPr fullCalcOnLoad="1" ', 1)
            open(pw, "w", encoding="utf-8").write(w)

        # ---- собираем книгу обратно ----
        if os.path.exists(куда):
            os.remove(куда)
        with zipfile.ZipFile(куда, "w", zipfile.ZIP_DEFLATED) as z:
            for корень, _, файлы in os.walk(временная):
                for f in файлы:
                    полный = os.path.join(корень, f)
                    z.write(полный, os.path.relpath(полный, временная))

        # ---- цифры для короткого сообщения в чат ----
        сводка = посчитать_сводку(просрочка, порт_обл)
        сводка["всего_строк"] = всего_строк
        сводка["без_области"] = без_области
        сводка["филиалы_не_в_отчёте"] = нет_в_отчёте
        return сводка
    finally:
        shutil.rmtree(временная, ignore_errors=True)


def посчитать_сводку(просрочка, порт_обл):
    """Те же цифры, что встанут в таблицу «СВОД ПО ОБЛАСТЯМ» на Дашборде."""
    строки = []
    портфель_всего = просрочка_всего = 0.0
    шт_всего = дозвон_всего = 0
    for обл, _ in ОБЛАСТИ:
        d = просрочка.get(обл, {s: [0.0, 0] for s in СТАТУСЫ})
        пр_сум = sum(d[s][0] for s in СТАТУСЫ)
        пр_шт = sum(d[s][1] for s in СТАТУСЫ)
        дозв = d["Дозвон"][1] + d["Обещал"][1]
        порт = порт_обл.get(обл, 0.0)
        строки.append({
            "область": обл, "портфель": порт, "просрочка": пр_сум,
            "процент": (пр_сум / порт if порт else 0.0),
            "шт": пр_шт, "дозвон": дозв,
        })
        портфель_всего += порт
        просрочка_всего += пр_сум
        шт_всего += пр_шт
        дозвон_всего += дозв
    # области, которых нет в списке 14 (например, опечатка в выгрузке)
    неизвестные = sorted(set(просрочка) - {о for о, _ in ОБЛАСТИ})
    return {
        "строки": строки,
        "портфель_всего": портфель_всего,
        "просрочка_всего": просрочка_всего,
        "процент_всего": (просрочка_всего / портфель_всего if портфель_всего else 0.0),
        "шт_всего": шт_всего,
        "дозвон_всего": дозвон_всего,
        "неизвестные_области": неизвестные,
    }


def текст_сводки(с):
    """Короткое сообщение в Telegram под файлом."""
    млрд = lambda v: "%.2f млрд" % (v / 1_000_000_000)
    строки = [
        "Отчёт готов.",
        "",
        "Обработано строк: %d" % с["всего_строк"],
        "Портфель: %s сум" % млрд(с["портфель_всего"]),
        "Просрочка: %s сум (%.1f%%), %d договоров"
        % (млрд(с["просрочка_всего"]), с["процент_всего"] * 100, с["шт_всего"]),
        "Дозвон + обещал: %d из %d" % (с["дозвон_всего"], с["шт_всего"]),
    ]
    if с["без_области"]:
        строки.append("")
        строки.append("Внимание: %d строк без области — они не попали в отчёт."
                      % с["без_области"])
    if с["неизвестные_области"]:
        строки.append("")
        строки.append("Внимание: незнакомые области (проверьте написание): %s"
                      % ", ".join(с["неизвестные_области"]))
    if с.get("филиалы_не_в_отчёте"):
        строки.append("")
        строки.append("Внимание: филиалы есть в кредитах, но их нет в таблице "
                      "отчёта: %s" % ", ".join(с["филиалы_не_в_отчёте"]))
    return "\n".join(строки)
